export function readJson(p) {
  return JSON.parse(fs.readFileSync(abs(p), "utf8"));
}

/** Every file the app is built from that can mention a CSS variable: src/**\/*.{css,ts,tsx} (tests too) + index.html. */
export function sourceFiles() {
  const out = [];
  const walk = (d) => {
    for (const e of fs.readdirSync(abs(d), { withFileTypes: true })) {
      const p = `${d}/${e.name}`;
      if (e.isDirectory()) walk(p);
      else if (/\.(css|ts|tsx)$/.test(e.name)) out.push(p);
    }
  };
  walk("src");
  out.push("index.html");
  return out.sort();
}

const blank = (s) => s.replace(/[^\n]/g, " ");

/**
 * Blank the comments of CSS / TS / TSX source (line structure kept), respecting string and template literals:
 * block comments everywhere, line comments in TS/TSX (a regex literal containing "//" is not expected in src/).
 */
export function stripComments(text, lineComments) {
  let out = "";
  let i = 0;
  const n = text.length;
  while (i < n) {
    const c = text[i];
    const d = text[i + 1];
    if (c === "/" && d === "*") {
      const j = text.indexOf("*/", i + 2);
      const end = j < 0 ? n : j + 2;
      out += blank(text.slice(i, end));
      i = end;
    } else if (lineComments && c === "/" && d === "/") {
      let j = text.indexOf("\n", i);
      if (j < 0) j = n;
      out += blank(text.slice(i, j));
      i = j;
    } else if (c === '"' || c === "'" || c === "`") {
      let j = i + 1;
      while (j < n && text[j] !== c) {
        if (text[j] === "\\") j++;
        else if (c !== "`" && text[j] === "\n") break; // unterminated: stop at the line end
        j++;
      }
      out += text.slice(i, j + 1);
      i = j + 1;
    } else {
      out += c;
      i++;
    }
  }
  return out;
}

/** A file's raw text with the GENERATED block of tokens.css / index.html blanked (line numbers kept). */
export function rawText(file) {
  const text = fs.readFileSync(abs(file), "utf8");
  if (file !== TOKENS_CSS && file !== INDEX_HTML) return text;
  const i = text.indexOf(BEGIN);
  const j = text.indexOf(END);
  return i >= 0 && j > i ? text.slice(0, i) + blank(text.slice(i, j)) + text.slice(j) : text;
}

/** The same text with its comments blanked (positions kept). */
export function codeText(file, raw = rawText(file)) {
  if (file.endsWith(".html")) return raw.replace(/<!--[\s\S]*?-->/g, blank);
  return stripComments(raw, /\.(ts|tsx)$/.test(file));
}

/**
 * Every `--th-*` mention outside the generated files: [{name, file, line, code, def}].
 * `code` = the mention is code, not a comment (comment stripping is lexical and conservative: a stray apostrophe in JSX
 * text can hide the rest of its line; the unknown-name check reads code mentions only).
 * `def` = it DEFINES the variable: a CSS declaration `--th-x:`, a style-object key `"--th-x":` /
 * `["--th-x" as string]:`, or `setProperty("--th-x"`. A trailing "-" (a `--th-font-*` glob) is not a mention.
 */
export function scanVars(files = sourceFiles()) {
  const hits = [];
  const re = /--th-[a-z0-9-]*[a-z0-9]/g;
  for (const file of files) {
    if (file === GEN_TS) continue;
    const raw = rawText(file);
    const code = codeText(file, raw);
    let m;
    re.lastIndex = 0;
    while ((m = re.exec(raw))) {
      const at = m.index;
      const end = at + m[0].length;
      const after = raw.slice(end, end + 40);
      const before = raw.slice(Math.max(0, at - 20), at);
      if (/^[a-z0-9-]/.test(after)) continue; // "--th-font-*"
      const isCode = code.slice(at, end) === m[0];
      let def = false;
      if (/\.(css|html)$/.test(file)) def = /^\s*:/.test(after) && !/var\(\s*$/.test(before);
      else def = /^["'`]\s*(as\s+string\s*)?\]?\s*:/.test(after) || /setProperty\(\s*["'`]$/.test(before);
      const line = raw.slice(0, at).split("\n").length;
      hits.push({ name: m[0], file, line, code: isCode, def: def && isCode });
    }
  }
  return hits;
}
