/** Picker filter (EP): keyword contains the query, or the emoji itself. */
export function filterEmoji(query: string): EmojiItem[] {
  const q = query.toLowerCase();
  if (!q) return EMOJI;
  return EMOJI.filter((x) => x.k.includes(q) || x.e === query);
}

/** ":ab" autocomplete (CV:1537-1573): keywords START with q (string start or after a space), first 8. */
export function completeEmoji(query: string): EmojiItem[] {
  const q = query.toLowerCase();
  return EMOJI.filter((x) => x.k.startsWith(q) || x.k.includes(" " + q)).slice(0, 8);
}
